"""Writes logic.entail.txt: the rules below, after a table of tokens and their events.

  python make_logic.py <tokenizer.json> <out.entail.txt>

A tokenizer merges symbols, so ((p is two brackets and a letter in two tokens. Each token
that is made only of logic is listed with the events it stands for, last event first.
"""
import json
import re
import sys

EVENTS = {"(": 12, ")": 13}
for names, code in [
    ("p", 1), ("q", 2), ("r", 3),
    ("true True TRUE T", 4), ("false False FALSE F", 5),
    ("not Not NOT ! ~ ¬", 6),
    ("and And AND & && ∧", 7), ("or Or OR | ||", 8), ("xor XOR ^ ⊕", 9),
    ("implies -> => →", 10), ("iff IFF <-> <=> ↔", 11),
]:
    for name in names.split():
        EVENTS[name] = code

# Tokens that cut a word: (NOT is (N|OT.
PIECES = {"(N": [12], " (N": [12], "((N": [12, 12], "OT": [6]}

LEX = re.compile("|".join(re.escape(k) for k in sorted(EVENTS, key=len, reverse=True)))

RULES = r"""# ═══════════════════════════════════════════════════════════════════════════
#  logic.entail — propositional logic
# ═══════════════════════════════════════════════════════════════════════════
#
#  Generated by make_logic.py. Edit the rules there.
#
#  An expression is evaluated once for each of the 8 assignments of p, q and r,
#  side by side. Constants come out as a value. With variables, the 8 results
#  say whether the expression always holds, never holds, or depends.
#
#    true and not false is                   true
#    (true or false) and false =             false
#    p or not p is                           a tautology
#    p and not p is                          a contradiction
#    p -> q is                               contingent
#    not (p and q) <-> not p or not q is     a tautology
#    Truth table of p xor q:                 0110
#
#  not binds tightest, then and, then or and xor, then -> and <->. Mixing or with
#  xor at one level, or using -> or <-> twice at one level, is ambiguous and
#  entails nothing, as does anything malformed. Brackets go two deep.
#
#  Table rows run with p slowest and false first.

program logic

const W = 30    # tokens in an expression
const E = 28    # events in an expression
const L = 3     # levels: the top, and two of brackets
const S = 10    # answer tokens

const V_NOT   = 6
const V_AND   = 7
const V_OR    = 8
const V_XOR   = 9
const V_IMP   = 10
const V_IFF   = 11
const V_OPEN  = 12
const V_CLOSE = 13

const K_IS    = 1
const K_EQ    = 2
const K_COLON = 3
const K_OF    = 4
const K_TABLE = 5

# ─── 1. Tokens ──────────────────────────────────────────────────────────────
#
# isx: this token can stand in an expression. cnt: how many events it holds.
# l1, l2, l3: those events, last first. an: an answer can hold it.

state isx, cnt, l1, l2, l3, an, kind

token " is" means kind = K_IS
token " =", "=" means kind = K_EQ
token ":" means kind = K_COLON
token "):" means kind = K_COLON, cnt = 1, l1 = 13
token ")):" means kind = K_COLON, cnt = 2, l1 = 13, l2 = 13
token ")=" means kind = K_EQ, cnt = 1, l1 = 13
token "))=" means kind = K_EQ, cnt = 2, l1 = 13, l2 = 13
token " of" means kind = K_OF
token " table" means kind = K_TABLE
token " " means isx = 1, an = 1
@TOKENS@

# ─── 2. Sight ───────────────────────────────────────────────────────────────

state wx[W + 2], wc[W + 2], w1[W + 2], w2[W + 2], w3[W + 2], wk[W + 3], wa_[S]
for k in 1 to W + 1
    attend back k
        wx[k] <- isx
        wc[k] <- cnt
        w1[k] <- l1
        w2[k] <- l2
        w3[k] <- l3
        wk[k] <- kind
    end
end
attend back W + 2
    wk[W + 2] <- kind
end
for k in 1 to S - 1
    attend back k
        wa_[k] <- an
    end
end

# ─── 3. The tokens become events ────────────────────────────────────────────
#
# Slot 0 is the last event before this token. Reading back, a token's last
# event stands after the events of every token behind it in the window.

state mk[W + 1], tot
entail tot = cnt
for i in 1 to W
    entail mk[i] when (sum j in 1 to i : wx[j]) >= i
    entail tot = wc[i] when mk[i]
end

state at[W + 1][E + 1], ev[E + 3]
# This token may hold closing brackets itself: ")" and ":" are often one token.
entail ev[0] = l1
entail ev[1] = l2
for i in 1 to W
    for r in 0 to E - 1
        entail at[i][r] when mk[i], cnt + (sum j in 1 to i-1 : wc[j]) == r
    end
end
for i in 1 to W
    for r in 0 to E - 1
        entail ev[r] = w1[i] when at[i][r]
        entail ev[r+1] = w2[i] when at[i][r]
        entail ev[r+2] = w3[i] when at[i][r]
    end
end

state is[E + 1][14]
for r in 0 to E - 1
    for t in 1 to 13
        entail is[r][t] when ev[r] == t
    end
    let lit[r] = (sum t in 1 to 5 : is[r][t])
    let bin[r] = (sum t in V_AND to V_IFF : is[r][t])
end

# ─── 4. Facts about each slot, the same for every assignment ────────────────

let dd[E - 1] = 0
for u in 2 to E
    const R = E - u
    let dd[R] = dd[R+1] + is[R+1][V_OPEN] - is[R+1][V_CLOSE]
end
let dEnd = dd[0] + is[0][V_OPEN] - is[0][V_CLOSE]

state dl[E][L + 1], gl[E][L], go[E][L], gc[E][L], gor[E][L], gim[E][L]
state xE[E][L], oE[E][L], iE[E][L], fE[E][L], tA[E][L], tO[E][L], tE[E][L]
for r in 0 to E - 1
    for l in 0 to L
        entail dl[r][l] when dd[r] == l
    end
    for l in 0 to L - 1
        entail gl[r][l] when dl[r][l], lit[r] >= 1
        entail xE[r][l] when dl[r][l], is[r][V_XOR]
        entail oE[r][l] when dl[r][l], is[r][V_OR]
        entail iE[r][l] when dl[r][l], is[r][V_IMP]
        entail fE[r][l] when dl[r][l], is[r][V_IFF]
        entail gor[r][l] when dl[r][l], is[r][V_XOR] + is[r][V_OR] >= 1
        entail gim[r][l] when dl[r][l], is[r][V_IMP] + is[r][V_IFF] >= 1
        if l < L - 1
            entail go[r][l] when dl[r][l], is[r][V_OPEN]
            entail gc[r][l] when dl[r][l+1], is[r][V_CLOSE]
        end
    end
    entail tA[r][0] when gl[r][0] + gc[r][0] + gor[r][0] + gim[r][0] >= 1
    entail tO[r][0] when gor[r][0] + gim[r][0] >= 1
    entail tE[r][0] when gim[r][0]
    for l in 1 to L - 1
        entail tA[r][l] when gl[r][l] + gc[r][l] + gor[r][l] + gim[r][l] + go[r][l-1] >= 1
        entail tO[r][l] when gor[r][l] + gim[r][l] + go[r][l-1] >= 1
        entail tE[r][l] when gim[r][l] + go[r][l-1] >= 1
    end
end

# What each level is waiting for, reading forwards from the oldest slot.
#   pn   a not is pending        sv   the bracket at this level was negated
#   pX   an xor is pending       pO   an or is pending
#   pI   an implication          pF   an equivalence
state pn[E + 1], sv[E + 1][L], pX[E + 1][L], pO[E + 1][L], pI[E + 1][L], pF[E + 1][L], faults
for u in 1 to E
    const T = E - u
    entail pn[T] when is[T][V_NOT], not pn[T+1]
    for l in 0 to L - 1
        if l == 0
            entail pX[T][l] when pX[T+1][l], not gim[T][l]
            entail pO[T][l] when pO[T+1][l], not gim[T][l]
            entail pI[T][l] when pI[T+1][l]
            entail pF[T][l] when pF[T+1][l]
        else
            entail sv[T][l] when sv[T+1][l], not go[T][l-1]
            entail sv[T][l] when go[T][l-1], pn[T+1]
            entail pX[T][l] when pX[T+1][l], not gim[T][l], not go[T][l-1]
            entail pO[T][l] when pO[T+1][l], not gim[T][l], not go[T][l-1]
            entail pI[T][l] when pI[T+1][l], not go[T][l-1]
            entail pF[T][l] when pF[T+1][l], not go[T][l-1]
        end
        entail pX[T][l] when xE[T][l]
        entail pO[T][l] when oE[T][l]
        entail pI[T][l] when iE[T][l]
        entail pF[T][l] when fE[T][l]
        # ambiguity
        entail faults when xE[T][l], pO[T+1][l]
        entail faults when oE[T][l], pX[T+1][l]
        entail faults when gim[T][l], pI[T+1][l]
        entail faults when gim[T][l], pF[T+1][l]
    end
end

# What may follow what. pe[r]: the slot before this one finished an operand.
for r in 0 to E - 1
    if r == E - 1
        entail faults when is[r][V_CLOSE]
        entail faults when bin[r] >= 1
    else
        entail faults when lit[r+1] + is[r+1][V_CLOSE] >= 1, lit[r] + is[r][V_OPEN] + is[r][V_NOT] >= 1
        entail faults when lit[r+1] + is[r+1][V_CLOSE] <= 0, bin[r] + is[r][V_CLOSE] >= 1
    end
    entail faults when is[r][V_CLOSE], dd[r] <= 0
    entail faults when is[r][V_OPEN], dd[r] >= L - 1
end

# ─── 5. The evaluation ──────────────────────────────────────────────────────
#
# For each assignment and level:
#   A  the current run of "and"      O  the "or" or "xor" of finished runs
#   F  what stands before a -> or <->
# V is the value of a level so far, and Vn the same after any not before its bracket.

state term[E][8]
for r in 0 to E - 1
    for a in 0 to 7
        const P = floor(a/4)
        const Q = floor(a/2) - 2*floor(a/4)
        const R3 = a - 2*floor(a/2)
        let lv = P*is[r][1] + Q*is[r][2] + R3*is[r][3] + is[r][4]
        entail term[r][a] when lv >= 1, not pn[r+1]
        entail term[r][a] when lit[r] >= 1, lv <= 0, pn[r+1]
    end
end

state A[E + 1][8*L], O[E + 1][8*L], F[E + 1][8*L], X[E + 1][8*L], V[E + 1][8*L], Vn[E + 1][8*L]
for x in 0 to 8*L - 1
    entail A[E][x] = 1
end

def value(T, l, a)
    const I = 8*l + a
    entail X[T][I] when not O[T][I], A[T][I]
    entail X[T][I] when O[T][I], not pX[T][l]
    entail X[T][I] when O[T][I], not A[T][I], pX[T][l]
    entail V[T][I] when X[T][I], not pI[T][l], not pF[T][l]
    entail V[T][I] when pI[T][l], not F[T][I]
    entail V[T][I] when pI[T][l], F[T][I], X[T][I]
    entail V[T][I] when pF[T][l], F[T][I], X[T][I]
    entail V[T][I] when pF[T][l], not F[T][I], not X[T][I]
end

for u in 1 to E
    const T = E - u
    const N = T + 1
    for l in 0 to L - 1
        for a in 0 to 7
            const I = 8*l + a
            if l > 0
                call value(N, l, a)
                entail Vn[N][I] when V[N][I], not sv[N][l]
                entail Vn[N][I] when not V[N][I], sv[N][l]
            end
        end
    end
    for l in 0 to L - 1
        for a in 0 to 7
            const I = 8*l + a
            entail A[T][I] when A[N][I], not tA[T][l]
            entail A[T][I] when gl[T][l], A[N][I], term[T][a]
            entail A[T][I] when gor[T][l]
            entail A[T][I] when gim[T][l]
            if l < L - 1
                entail A[T][I] when gc[T][l], A[N][I], Vn[N][I + 8]
            end
            if l > 0
                entail A[T][I] when go[T][l-1]
            end

            entail O[T][I] when O[N][I], not tO[T][l]
            entail O[T][I] when gor[T][l], not O[N][I], A[N][I]
            entail O[T][I] when gor[T][l], O[N][I], not pX[N][l]
            entail O[T][I] when gor[T][l], O[N][I], not A[N][I], pX[N][l]

            entail F[T][I] when F[N][I], not tE[T][l]
            entail F[T][I] when gim[T][l], not O[N][I], A[N][I]
            entail F[T][I] when gim[T][l], O[N][I], not pX[N][l]
            entail F[T][I] when gim[T][l], O[N][I], not A[N][I], pX[N][l]
        end
    end
end
for a in 0 to 7
    call value(0, 0, a)
end

# ─── 6. The verdict ─────────────────────────────────────────────────────────

state uP, uQ, uR
let total = (sum a in 0 to 7 : V[0][a])
let nOps = (sum r in 0 to E - 1 : bin[r] + is[r][V_NOT])
entail uP when (sum r in 0 to E - 1 : is[r][1]) >= 1
entail uQ when (sum r in 0 to E - 1 : is[r][2]) >= 1
entail uR when (sum r in 0 to E - 1 : is[r][3]) >= 1

state wellFormed, asked, tableAsked, st[W + 1]
entail wellFormed when tot >= 2, tot <= E, faults <= 0, dEnd == 0, lit[0] + is[0][V_CLOSE] >= 1, nOps >= 1, not mk[W]
entail asked when kind == K_IS, wellFormed
entail asked when kind == K_EQ, wellFormed
for i in 2 to W
    entail st[i] when mk[i-1], not wx[i]
    entail tableAsked when st[i], kind == K_COLON, wellFormed, wk[i] == K_OF, wk[i+1] == K_TABLE
end

state vars, vTrue, vFalse, vAlways, vNever, vDepends
entail vars when uP + uQ + uR >= 1
entail vTrue when asked, not vars, total >= 8
entail vFalse when asked, not vars, total <= 0
entail vAlways when asked, vars, total >= 8
entail vNever when asked, vars, total <= 0
entail vDepends when asked, vars, total >= 1, total <= 7

state t8, t4, t2
entail t8 when tableAsked, uR
entail t4 when tableAsked, not uR, uQ
entail t2 when tableAsked, not uR, not uQ, uP

# ─── 7. The answer ──────────────────────────────────────────────────────────

const C_ZERO   = 1
const C_BLANK  = 3
const C_TRUE   = 4
const C_FALSE  = 5
const C_A      = 6
const C_CONTRA = 7
const C_DEPEND = 8
const C_END    = 9
const C_WORD   = 10    # the pieces of " tautology"

state code[S]
entail code[0] = C_TRUE when vTrue
entail code[1] = C_END when vTrue
entail code[0] = C_FALSE when vFalse
entail code[1] = C_END when vFalse
entail code[0] = C_DEPEND when vDepends
entail code[1] = C_END when vDepends
entail code[0] = C_A when vNever
entail code[1] = C_CONTRA when vNever
entail code[2] = C_END when vNever
entail code[0] = C_A when vAlways
@ALWAYS@

entail code[0] = C_BLANK when t8
for a in 0 to 7
    entail code[1+a] = V[0][a] + 1 when t8
end
entail code[9] = C_END when t8
entail code[0] = C_BLANK when t4
for i in 0 to 3
    entail code[1+i] = V[0][2*i] + 1 when t4
end
entail code[5] = C_END when t4
entail code[0] = C_BLANK when t2
entail code[1] = V[0][0] + 1 when t2
entail code[2] = V[0][4] + 1 when t2
entail code[3] = C_END when t2

state anc
entail anc when vTrue
entail anc when vFalse
entail anc when vDepends
entail anc when vNever
entail anc when vAlways
entail anc when t8
entail anc when t4
entail anc when t2

state wa[S]
for c in 1 to S - 1
    attend back c
        wa[c] <- anc
    end
end

let aa[0] = an
for k in 1 to S - 1
    let aa[k] = wa_[k]
end

state from[S], slot[S]
entail from[0] when anc
entail slot[0] when anc
for c in 1 to S - 1
    entail from[c] when wa[c], (sum i in 0 to c-1 : aa[i]) >= c
    entail slot[c] when wa[c], (sum i in 0 to c-1 : aa[i]) >= c
end

state seen[S]
attend back by from
    for s in 0 to S-1
        seen[s] <- code[s]
    end
end

state say
for s in 0 to S-1
    entail say = seen[s] when slot[s]
end

state o[C_WORD + 5]
for d in 1 to C_WORD + 4
    entail o[d] when say == d
end
emit "0" when o[1]
emit "1" when o[2]
emit " " when o[C_BLANK]
emit " true" when o[C_TRUE]
emit " false" when o[C_FALSE]
emit " a" when o[C_A]
emit " contradiction" when o[C_CONTRA]
emit " contingent" when o[C_DEPEND]
@WORD@
emit end when o[C_END]
"""


def events(token):
    """The token's events, or None if it is not made only of logic."""
    if token in PIECES:
        return PIECES[token]
    text = token.lstrip(" ")
    if len(token) - len(text) > 1 or not text:
        return None
    found, at = [], 0
    while at < len(text):
        m = LEX.match(text, at)
        if not m:
            return None
        found.append(m.group())
        at = m.end()
    if len(found) > 3:
        return None
    words = [w[0].isalpha() for w in found]
    if any(a and b for a, b in zip(words, words[1:])):
        return None
    return [EVENTS[w] for w in found]


def token_line(token, codes, answer):
    parts = ["isx = 1", f"cnt = {len(codes)}"]
    for i, code in enumerate(reversed(codes)):
        parts.append(f"l{i + 1} = {code}")
    if answer:
        parts.append("an = 1")
    return f'token "{token}" means ' + ", ".join(parts)


def main():
    from tokenizers import Tokenizer
    with open(sys.argv[1], encoding="utf8") as f:
        vocabulary = json.load(f)["model"]["vocab"]
    t = Tokenizer.from_file(sys.argv[1])
    words = sorted({t.decode([i]) for i in vocabulary.values()})
    pieces = [t.decode([i]) for i in t.encode(" tautology", add_special_tokens=False).ids]
    said = {" a", " contradiction", " contingent", *pieces}
    lines = []
    for w in words:
        codes = events(w)
        if codes:
            lines.append(token_line(w, codes, w in (" true", " false")))
    lines.append('token "0" means isx = 1, cnt = 1, l1 = 5, an = 1')
    lines.append('token "1" means isx = 1, cnt = 1, l1 = 4, an = 1')
    for w in sorted(said):
        lines.append(f'token "{w}" means an = 1')
    always = [f"entail code[{i + 1}] = C_WORD + {i} when vAlways" for i in range(len(pieces))]
    always.append(f"entail code[{len(pieces) + 1}] = C_END when vAlways")
    emits = [f'emit "{w}" when o[C_WORD + {i}]' for i, w in enumerate(pieces)]
    text = (RULES.replace("@TOKENS@", "\n".join(lines)).replace("@ALWAYS@", "\n".join(always))
            .replace("@WORD@", "\n".join(emits)))
    with open(sys.argv[2], "w", encoding="utf8", newline="\n") as f:
        f.write(text)
    print(len(lines), "tokens;", "tautology is", pieces)


if __name__ == "__main__":
    main()
